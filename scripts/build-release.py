#!/usr/bin/env python3
"""
Build the downloadable NOVA source release and record its real details.

The download page must not invent a file size or checksum, so this script
zips the released interpreter, hashes it, and writes the numbers the site
displays. Re-run it whenever the interpreter changes.

Usage:
    python3 scripts/build-release.py [--nova DIR]

Produces:
    client/public/downloads/nova-1.0.0.zip
    client/src/content/downloads.generated.ts
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import sys
import tempfile
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VERSION = "1.0.0"
ARTEFACT = f"nova-{VERSION}.zip"

# What a learner needs. Tests and packaging notes stay in the repository,
# not in the download, so the folder stays small and readable.
INCLUDE_FILES = ["nova.py", "README.md"]
INCLUDE_DIRS = ["novalang", "examples"]
SKIP_NAMES = {"__pycache__", ".DS_Store", ".git", "packaging", "tests"}


def find_release(explicit: str | None) -> Path:
    if explicit:
        candidate = Path(explicit).resolve()
        if (candidate / "nova.py").is_file():
            return candidate
        sys.exit(f"No nova.py inside {candidate}")

    for candidate in (ROOT.parent / "nova", ROOT / "nova"):
        if (candidate / "nova.py").is_file():
            return candidate.resolve()

    sys.exit("Could not find the interpreter. Pass it with --nova /path/to/nova")


def add_tree(archive: zipfile.ZipFile, source: Path, arcroot: str) -> list[str]:
    added: list[str] = []
    for path in sorted(source.rglob("*")):
        if any(part in SKIP_NAMES for part in path.parts):
            continue
        if path.is_dir():
            continue
        if path.suffix == ".pyc":
            continue
        arcname = f"{arcroot}/{path.relative_to(source).as_posix()}"
        # Fixed timestamps keep the hash stable across rebuilds.
        info = zipfile.ZipInfo(arcname, date_time=(2026, 9, 12, 0, 0, 0))
        info.compress_type = zipfile.ZIP_DEFLATED
        info.external_attr = 0o644 << 16
        archive.writestr(info, path.read_bytes())
        added.append(arcname)
    return added


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--nova", help="folder holding nova.py (default: ../nova)")
    args = parser.parse_args()

    release = find_release(args.nova)
    target_dir = ROOT / "client" / "public" / "downloads"
    target_dir.mkdir(parents=True, exist_ok=True)
    target = target_dir / ARTEFACT

    with tempfile.TemporaryDirectory(prefix="nova-release-") as tmp:
        staging = Path(tmp) / f"nova-{VERSION}"
        staging.mkdir()

        for name in INCLUDE_FILES:
            source = release / name
            if not source.is_file():
                sys.exit(f"Missing {name} in {release}")
            shutil.copy2(source, staging / name)

        for name in INCLUDE_DIRS:
            source = release / name
            if not source.is_dir():
                sys.exit(f"Missing folder {name} in {release}")
            shutil.copytree(
                source,
                staging / name,
                ignore=shutil.ignore_patterns(*SKIP_NAMES, "*.pyc"),
            )

        with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED) as archive:
            entries = add_tree(archive, staging, f"nova-{VERSION}")

    digest = hashlib.sha256(target.read_bytes()).hexdigest()
    size = target.stat().st_size
    lessons = sorted(p.name for p in (release / "examples").glob("[0-9][0-9]_*.nova"))
    examples = sorted(p.name for p in (release / "examples").glob("*.nova"))

    payload = {
        "version": VERSION,
        "filename": ARTEFACT,
        "url": f"/downloads/{ARTEFACT}",
        "bytes": size,
        "sha256": digest,
        "fileCount": len(entries),
        "lessonCount": len(lessons),
        "exampleCount": len(examples),
        "entries": entries,
    }

    out = ROOT / "client" / "src" / "content" / "downloads.generated.ts"
    out.write_text(
        "// Generated by scripts/build-release.py — do not edit by hand.\n"
        "// Every number here comes from the artefact actually shipped.\n"
        f"export const releaseData = {json.dumps(payload, indent=2)} as const;\n",
        encoding="utf-8",
    )

    print(f"  {ARTEFACT}  {size:,} bytes  {len(entries)} files")
    print(f"  sha256 {digest}")
    print(f"  wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
